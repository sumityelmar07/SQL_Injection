import os
import warnings

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

_INSECURE_DEFAULT_KEY = "dev-only-change-in-prod-abc123"

def _resolve_secret_key() -> str:
    key = os.environ.get("SECRET_KEY")
    if not key:
        warnings.warn(
            "SECRET_KEY environment variable is not set. "
            "An insecure default is being used. "
            "Set SECRET_KEY before connecting this app to a network.",
            RuntimeWarning,
            stacklevel=2,
        )
        return _INSECURE_DEFAULT_KEY
    return key


class Config:
    # Flask secret key — signs session cookies so they cannot be tampered with.
    # Set the SECRET_KEY environment variable to a long random string before
    # running on any machine accessible to other people.
    SECRET_KEY = _resolve_secret_key()

    # Rate limiting storage backend (uses memory storage for local demonstration)
    RATELIMIT_STORAGE_URI = "memory://"

    # Path to the main application database (users table).
    DATABASE = os.path.join(BASE_DIR, "instance", "app.db")

    # Path to the attack-log database (separate so it is never mixed with user data).
    ATTACK_LOG_DB = os.path.join(BASE_DIR, "logs", "attacks.db")

    # Path to the trained ML model file produced by ml/train.py.
    MODEL_PATH = os.path.join(BASE_DIR, "ml", "model.pkl")

    # Risk score thresholds that control what happens to a request.
    RISK_SUSPICIOUS = 30
    RISK_BLOCK = 60
    RISK_DEFINITE = 80

    # Weights used when combining the three detection signals into a final score.
    # Must sum to 1.0.
    WEIGHT_SIGNATURE = 0.40
    WEIGHT_ANOMALY = 0.25
    WEIGHT_ML = 0.35

    # Bcrypt password hashing cost factor (12 is a good balance of speed vs security).
    BCRYPT_LOG_ROUNDS = 12

    # CSRF protection (Flask-WTF).
    # Every POST form must include the hidden csrf_token field generated by
    # {{ csrf_token() }} in the template.
    WTF_CSRF_ENABLED = True
    WTF_CSRF_TIME_LIMIT = 3600      # token expires after 1 hour

    # Flask session cookie settings.
    SESSION_COOKIE_HTTPONLY = True   # JavaScript cannot read the cookie.
    SESSION_COOKIE_SAMESITE = "Lax"  # Limits cross-site request exposure.
